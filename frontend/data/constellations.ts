export function getConstellationById(id: string): Constellation | undefined {
  return CONSTELLATIONS.find((c) => c.id === id);
}

export function getStarById(id: string): StarDetail | undefined {
  return STARS.find((s) => s.id === id);
}

export function getConstellationByDate(month: number, day: number): Constellation {
  // Month: 1-12, Day: 1-31
  // Zodiac date ranges
  if ((month === 3 && day >= 21) || (month === 4 && day <= 19)) {
    return getConstellationById("aries") || CONSTELLATIONS[0];
  } else if ((month === 4 && day >= 20) || (month === 5 && day <= 20)) {
    return getConstellationById("taurus") || CONSTELLATIONS[0];
  } else if ((month === 5 && day >= 21) || (month === 6 && day <= 20)) {
    return getConstellationById("gemini") || CONSTELLATIONS[0];
  } else if ((month === 6 && day >= 21) || (month === 7 && day <= 22)) {
    return getConstellationById("canis-major") || CONSTELLATIONS[0];
  } else if ((month === 7 && day >= 23) || (month === 8 && day <= 22)) {
    return getConstellationById("leo") || CONSTELLATIONS[0];
  } else if ((month === 8 && day >= 23) || (month === 9 && day <= 22)) {
    return getConstellationById("cygnus") || CONSTELLATIONS[0];
  } else if ((month === 9 && day >= 23) || (month === 10 && day <= 22)) {
    return getConstellationById("cassiopeia") || CONSTELLATIONS[0];
  } else if ((month === 10 && day >= 23) || (month === 11 && day <= 21)) {
    return getConstellationById("scorpius") || CONSTELLATIONS[0];
  } else if ((month === 11 && day >= 22) || (month === 12 && day <= 21)) {
    return getConstellationById("orion") || CONSTELLATIONS[0];
  } else if ((month === 12 && day >= 22) || (month === 1 && day <= 19)) {
    return getConstellationById("ursa-major") || CONSTELLATIONS[0];
  } else if ((month === 1 && day >= 20) || (month === 2 && day <= 18)) {
    return getConstellationById("aquarius") || CONSTELLATIONS[0];
  } else {
    return getConstellationById("ursa-minor") || CONSTELLATIONS[0];
  }
}
